#!/usr/bin/env python3
"""
Convert images to an Arduino header (images.h) of RGB565 arrays
for a 1.8" ST7735 TFT (160x128 landscape).

Usage:
    pip install pillow
    python make_images_h.py                 # uses all images in ./images
    python make_images_h.py my_pics         # uses all images in ./my_pics
    python make_images_h.py a.jpg b.png ... # explicit files, in this order

Options:
    --width 160 --height 128   target size (default landscape 160x128)
    --mode crop|fit|stretch    crop = fill screen, trim edges (default)
                               fit  = keep whole image, black bars
                               stretch = distort to fill
    --swap-rb                  swap red/blue if colours look wrong on screen
    --out images.h             output file name
"""
import argparse
import os
import sys

from PIL import Image, ImageOps

EXTS = (".jpg", ".jpeg", ".png", ".bmp", ".gif", ".webp")


def collect(inputs):
    if not inputs:
        inputs = ["images"]
    if len(inputs) == 1 and os.path.isdir(inputs[0]):
        folder = inputs[0]
        files = sorted(
            os.path.join(folder, f)
            for f in os.listdir(folder)
            if f.lower().endswith(EXTS)
        )
    else:
        files = inputs
    return files


def resize(img, w, h, mode):
    img = ImageOps.exif_transpose(img).convert("RGB")
    if mode == "crop":
        return ImageOps.fit(img, (w, h), Image.LANCZOS)
    if mode == "fit":
        return ImageOps.pad(img, (w, h), Image.LANCZOS, color=(0, 0, 0))
    return img.resize((w, h), Image.LANCZOS)


def to_rgb565(img, swap_rb):
    out = []
    for r, g, b in img.getdata():
        if swap_rb:
            r, b = b, r
        out.append(((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3))
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("inputs", nargs="*")
    ap.add_argument("--width", type=int, default=160)
    ap.add_argument("--height", type=int, default=128)
    ap.add_argument("--mode", choices=["crop", "fit", "stretch"], default="crop")
    ap.add_argument("--swap-rb", action="store_true")
    ap.add_argument("--out", default="images.h")
    a = ap.parse_args()

    files = collect(a.inputs)
    if not files:
        sys.exit("No images found.")

    lines = [
        "// Auto-generated by make_images_h.py - do not edit",
        "#pragma once",
        "#include <Arduino.h>",
        "",
        f"#define IMG_W {a.width}",
        f"#define IMG_H {a.height}",
        f"#define NUM_IMAGES {len(files)}",
        "",
    ]

    for i, path in enumerate(files):
        print(f"[{i}] {path}")
        img = resize(Image.open(path), a.width, a.height, a.mode)
        data = to_rgb565(img, a.swap_rb)
        lines.append(f"// {os.path.basename(path)}")
        lines.append(f"const uint16_t img{i}[{len(data)}] PROGMEM = {{")
        for j in range(0, len(data), 12):
            chunk = ", ".join(f"0x{v:04X}" for v in data[j : j + 12])
            lines.append("  " + chunk + ",")
        lines.append("};")
        lines.append("")

    names = ", ".join(f"img{i}" for i in range(len(files)))
    lines.append(f"const uint16_t* const images[NUM_IMAGES] = {{ {names} }};")
    lines.append("")

    with open(a.out, "w") as f:
        f.write("\n".join(lines))

    kb = len(files) * a.width * a.height * 2 / 1024
    print(f"Wrote {a.out} ({len(files)} images, ~{kb:.0f} KB of flash)")


if __name__ == "__main__":
    main()
